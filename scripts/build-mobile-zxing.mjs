import { build } from 'esbuild'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const wasmPath = join(root, 'node_modules', 'zxing-wasm', 'dist', 'reader', 'zxing_reader.wasm')
const outPath = join(root, 'src', 'main', 'lan', 'zxing-wasm.browser.js')

const wasmBase64 = readFileSync(wasmPath).toString('base64')

const source = `
import { prepareZXingModule, readBarcodes } from 'zxing-wasm/reader'

const WASM_BASE64 = ${JSON.stringify(wasmBase64)}

prepareZXingModule({
  overrides: {
    wasmBinary: Uint8Array.from(atob(WASM_BASE64), c => c.charCodeAt(0))
  }
})

export async function decodeBarcodeFile(file) {
  const results = await readBarcodes(file, {
    tryHarder: true,
    formats: ['EANUPC', 'Code128', 'Code39', 'ITF', 'QRCode'],
    maxNumberOfSymbols: 1
  })
  return results.length > 0 ? results[0].text : null
}
`

const result = await build({
  stdin: {
    contents: source,
    resolveDir: root,
    sourcefile: 'mobile-zxing-entry.js',
    loader: 'js'
  },
  bundle: true,
  format: 'iife',
  globalName: 'ZXingWasmReader',
  platform: 'browser',
  target: ['es2020'],
  minify: true,
  write: false
})

mkdirSync(dirname(outPath), { recursive: true })
const code = `/* Generated by scripts/build-mobile-zxing.mjs — do not edit. */\n${result.outputFiles[0].text}`
writeFileSync(outPath, code)
console.log(`[mobile-zxing] wrote ${outPath} (${Buffer.byteLength(code) / 1024 / 1024} MiB)`)
